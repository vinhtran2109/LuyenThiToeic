export type Question = {
  id: string;
  testId: string;
  number: number;
  part: number;
  groupId: string;
  prompt: string;
  options: string[];
  passage: string;
  image?: string;
  answer?: string;
  confirmed: boolean;
  explanation?: string;
  sourcePage?: number;
  sourcePages?: { page: number; url: string }[];
  needsReview?: boolean;
};
export type Test = {
  id: string;
  title: string;
  year: number;
  collection: string;
  description: string;
  questions?: Question[];
  attempts: Attempt[];
  mappings?: Mapping[];
  section?: string;
  sourceDocumentId?: string;
  sourceStartPage?: number;
  sourceEndPage?: number;
  _count?: { questions: number };
  keyCounts?: { reading: number; listening: number };
};
export type Attempt = {
  id: string;
  testId: string;
  test?: Test;
  mode: string;
  section: string;
  status: string;
  startedAt: string;
  deadline: string;
  completedAt?: string;
  current: number;
  answers: Record<string, string>;
  flags: number[];
  correct?: number;
  gradable?: number;
  score?: number;
  elapsed: number;
  audioIndex: number;
  audioPosition: number;
  phase: string;
};
export type Doc = {
  id: string;
  name: string;
  kind: string;
  path: string;
  mime: string;
  size: number;
  status: string;
  text: string;
  createdAt: string;
};
export type Mapping = {
  id: string;
  testId: string;
  documentId: string;
  document: Doc;
  part: number;
  questionStart: number;
  questionEnd: number;
  groupId: string;
  start: number;
  end: number;
  sequence: number;
  gap: number;
  confirmed?: boolean;
  continuous?: boolean;
  playbackStart?: number;
  playbackEnd?: number;
};
